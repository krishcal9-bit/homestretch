// Generates components/brand/wordmarkGlyphs.ts: "Keystone" in Fraunces (opsz 144, wght 600, SOFT 30, WONK 0 — the
// static instance scripts/fonts/keystone-wordmark.ttf, cut from the variable font with fontTools) as SVG outlines,
// em = 100, baseline y = 0, tracking -0.02em, kerning applied; plus the brass keystone notch set into the top of
// the K's stem (the stem spans 202–482 font units under the serif; cap height 1400 of 2000).
// Run: node scripts/build-wordmark.mjs
import opentype from 'opentype.js';
import fs from 'fs';
const font = opentype.loadSync('scripts/fonts/keystone-wordmark.ttf');
const EM = 100;
const s = EM / font.unitsPerEm;
const TRACK = -0.02 * EM;
const text = 'Keystone';
let x = 0;
const letters = [];
const glyphs = font.stringToGlyphs(text);
glyphs.forEach((g, i) => {
  const path = g.getPath(x, 0, EM);
  const bb = path.getBoundingBox();
  letters.push({ ch: text[i], d: path.toPathData(2), x: +x.toFixed(2), adv: +(g.advanceWidth * s).toFixed(2), x1: +bb.x1.toFixed(2), x2: +bb.x2.toFixed(2), y1: +bb.y1.toFixed(2), y2: +bb.y2.toFixed(2) });
  const kern = i < glyphs.length - 1 ? font.getKerningValue(g, glyphs[i + 1]) * s : 0;
  x += g.advanceWidth * s + kern + (i < glyphs.length - 1 ? TRACK : 0);
});
// the notch: a keystone wedge (wider at the top) at the top of the K's stem, through the serif
const cx = 342 * s;
const top = -1400 * s - 0.6;
const depth = 230 * s;
const tw = 160 * s;
const bw = 100 * s;
const notch = `M${(cx - tw / 2).toFixed(2)} ${top.toFixed(2)}H${(cx + tw / 2).toFixed(2)}L${(cx + bw / 2).toFixed(2)} ${(top + depth).toFixed(2)}H${(cx - bw / 2).toFixed(2)}Z`;
const out = { em: EM, width: +x.toFixed(2), capHeight: 1400 * s, ascender: +(font.ascender * s).toFixed(2), descender: +(font.descender * s).toFixed(2), letters, notch, notchBox: { x: +(cx - tw / 2).toFixed(2), y: +top.toFixed(2), w: +tw.toFixed(2), h: +depth.toFixed(2) } };
fs.writeFileSync('components/brand/wordmarkGlyphs.ts', `// Generated by scripts/build-wordmark.mjs from Fraunces (OFL) at opsz 144, wght 600, SOFT 30, WONK 0. Do not edit by hand.\nexport const WORDMARK = ${JSON.stringify(out, null, 1)} as const;\n`);
console.log('width', out.width, 'notch', notch);
