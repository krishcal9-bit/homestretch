// Generates components/brand/wordmarkGlyphs.ts: "Keystone" in Public Sans 600 and 700 as SVG outlines (the wordmark uses 700)
// (em = 100 units, baseline y = 0, tracking -0.03em, font kerning applied). Run: node scripts/build-wordmark.mjs
import opentype from 'opentype.js';
import fs from 'fs';
function build(file) {
  const font = opentype.loadSync(file);
  const EM = 100;
  const scale = EM / font.unitsPerEm;
  const TRACK = -0.03 * EM;
  const text = 'Keystone';
  let x = 0;
  const letters = [];
  const glyphs = font.stringToGlyphs(text);
  glyphs.forEach((g, i) => {
    const path = g.getPath(x, 0, EM);
    const bb = path.getBoundingBox();
    letters.push({ ch: text[i], d: path.toPathData(2), x: +x.toFixed(2), x1: +bb.x1.toFixed(2), x2: +bb.x2.toFixed(2), y1: +bb.y1.toFixed(2), y2: +bb.y2.toFixed(2) });
    const kern = i < glyphs.length - 1 ? font.getKerningValue(g, glyphs[i + 1]) * scale : 0;
    x += g.advanceWidth * scale + kern + (i < glyphs.length - 1 ? TRACK : 0);
  });
  return {
    em: EM,
    width: +x.toFixed(2),
    ascender: +(font.ascender * scale).toFixed(2),
    descender: +(font.descender * scale).toFixed(2),
    capHeight: +((font.tables.os2.sCapHeight || 700) * scale).toFixed(2),
    xHeight: +((font.tables.os2.sxHeight || 500) * scale).toFixed(2),
    letters,
  };
}
const dir = 'node_modules/@fontsource/public-sans/files/';
const g600 = build(dir + 'public-sans-latin-600-normal.woff');
const g700 = build(dir + 'public-sans-latin-700-normal.woff');
fs.writeFileSync(
  'components/brand/wordmarkGlyphs.ts',
  `// Generated by scripts/build-wordmark.mjs from Public Sans 600 and 700 (OFL). Do not edit by hand.\nexport const GLYPHS = ${JSON.stringify(g600, null, 1)} as const;\nexport const GLYPHS_BOLD = ${JSON.stringify(g700, null, 1)} as const;\n`,
);
console.log('600 width', g600.width, 'cap', g600.capHeight, '| 700 width', g700.width, 'cap', g700.capHeight);
